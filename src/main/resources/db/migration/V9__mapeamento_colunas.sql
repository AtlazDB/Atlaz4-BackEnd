-- GeoRural DataHub — Mapeamento de colunas da fonte
--------------------------------------------------------------------------------
-- Banco......: Oracle Database (Autonomous / ATP)
-- Encoding...: UTF-8 (AL32UTF8) — abra o arquivo em UTF-8 ou os acentos quebram
-- Escopo.....: Sprint 2, Tarefa 5 — modal de mapeamento de colunas
-- Depende de.: V1 (fonte, arquivo_bruto). Não depende da V8.
--
--------------------------------------------------------------------------------
-- O QUE ESTE SCRIPT CRIA
--------------------------------------------------------------------------------
--   dominio         lista nomeada de valores permitidos (ex.: situação do CAR)
--   dominio_valor   os valores de cada domínio
--   fonte_coluna    colunas detectadas nos arquivos de uma fonte (quem grava é
--                   a DAG detectar_colunas, da Tarefa 1)
--   regra_campo     o mapeamento: coluna de origem -> campo de destino, com as
--                   regras de qualidade. É a tabela que o pkg_qualidade lê
--                   (Tarefa 2).
--
-- E altera uma coisa existente: o status de arquivo_bruto ganha
-- AGUARDANDO_MAPEAMENTO (seção 3).
--
--------------------------------------------------------------------------------
-- O QUE ESTE SCRIPT **NÃO** FAZ
--------------------------------------------------------------------------------
-- Nenhum INSERT. A carga dos domínios e o seed do CAR entram em seguida, neste
-- mesmo arquivo, antes do merge na dev.
--
-- A situação da coluna (mapeada / nova / ausente) NÃO é gravada. É derivada:
--   ausente = fonte_coluna.presente_ultimo_arquivo = 0
--   mapeada = existe linha em regra_campo para a coluna
--   nova    = presente no último arquivo e sem linha em regra_campo
--
--------------------------------------------------------------------------------
-- COMO RODAR
--------------------------------------------------------------------------------
-- Via Flyway, na subida da aplicação, depois de V1..V8.
-- Não editar depois de aplicado em qualquer ambiente (quebra o checksum do
-- Flyway) — qualquer ajuste vira uma migration nova.
--------------------------------------------------------------------------------


--------------------------------------------------------------------------------
-- SEÇÃO 1 — TABELAS
--------------------------------------------------------------------------------

-- 1.1 DOMINIO ----------------------------------------------------------------
-- Lista nomeada de valores permitidos. O código é a chave de negócio.
CREATE TABLE dominio (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  codigo     VARCHAR2(60  CHAR) NOT NULL,
  nome       VARCHAR2(160 CHAR) NOT NULL,
  descricao  VARCHAR2(400 CHAR),
  ativo      NUMBER(1)          DEFAULT 1 NOT NULL,
  criado_em  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_dominio        PRIMARY KEY (id),
  CONSTRAINT uk_dominio_codigo UNIQUE (codigo),
  CONSTRAINT ck_dominio_ativo  CHECK (ativo IN (0,1))
);


-- 1.2 DOMINIO_VALOR ----------------------------------------------------------
CREATE TABLE dominio_valor (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  dominio_id  NUMBER             NOT NULL,
  valor       VARCHAR2(100 CHAR) NOT NULL,
  descricao   VARCHAR2(300 CHAR),
  ordem       NUMBER(5)          DEFAULT 0 NOT NULL,
  ativo       NUMBER(1)          DEFAULT 1 NOT NULL,
  CONSTRAINT pk_dominio_valor   PRIMARY KEY (id),
  CONSTRAINT fk_domval_dominio  FOREIGN KEY (dominio_id) REFERENCES dominio (id),
  CONSTRAINT uk_domval          UNIQUE (dominio_id, valor),
  CONSTRAINT ck_domval_ativo    CHECK (ativo IN (0,1))
);


-- 1.3 FONTE_COLUNA -----------------------------------------------------------
-- Uma linha por coluna já vista em algum arquivo da fonte. A DAG faz MERGE aqui
-- a cada arquivo recebido (o usuário Oracle do Airflow não tem DDL, só DML).
CREATE TABLE fonte_coluna (
  id                       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fonte_id                 NUMBER             NOT NULL,
  nome_coluna              VARCHAR2(128 CHAR) NOT NULL,
  tipo_detectado           VARCHAR2(40  CHAR),
  exemplos                 CLOB,
  ordem                    NUMBER(5),
  presente_ultimo_arquivo  NUMBER(1)          DEFAULT 1 NOT NULL,
  primeira_deteccao        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  ultima_deteccao          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_fonte_coluna   PRIMARY KEY (id),
  CONSTRAINT fk_fcol_fonte     FOREIGN KEY (fonte_id) REFERENCES fonte (id),
  CONSTRAINT uk_fcol           UNIQUE (fonte_id, nome_coluna),
  CONSTRAINT ck_fcol_exemplos  CHECK (exemplos IS JSON),
  CONSTRAINT ck_fcol_presente  CHECK (presente_ultimo_arquivo IN (0,1))
);


-- 1.4 REGRA_CAMPO ------------------------------------------------------------
-- Uma linha = uma coluna de origem mapeada para um campo de destino, com as
-- regras de qualidade daquele campo. Remover o mapeamento = apagar a linha
-- (a coluna volta a aparecer como "nova").
CREATE TABLE regra_campo (
  id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fonte_id            NUMBER             NOT NULL,
  fonte_coluna_id     NUMBER             NOT NULL,

  -- destino da gravação: tabela e campo (ex.: imovel_rural / cod_imovel)
  destino_tabela      VARCHAR2(60 CHAR)  NOT NULL,
  campo_destino       VARCHAR2(60 CHAR)  NOT NULL,

  -- tipo e formato
  tipo_dado           VARCHAR2(20 CHAR)  NOT NULL,
  formato_origem      VARCHAR2(60 CHAR),

  -- caixas de regra
  obrigatorio         NUMBER(1) DEFAULT 0 NOT NULL,
  chave               NUMBER(1) DEFAULT 0 NOT NULL,
  bloquear_regressao  NUMBER(1) DEFAULT 0 NOT NULL,
  validar_cpf_cnpj    NUMBER(1) DEFAULT 0 NOT NULL,

  -- geometria (só quando tipo_dado = GEOMETRIA)
  politica_geometria  VARCHAR2(30 CHAR),
  recortar_pr         NUMBER(1) DEFAULT 0 NOT NULL,

  -- domínio e integridade cruzada (ambos opcionais)
  dominio_id          NUMBER,
  referencia_cruzada  VARCHAR2(30 CHAR),

  criado_em           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT pk_regra_campo    PRIMARY KEY (id),
  CONSTRAINT fk_regra_fonte    FOREIGN KEY (fonte_id)        REFERENCES fonte (id),
  CONSTRAINT fk_regra_fcol     FOREIGN KEY (fonte_coluna_id) REFERENCES fonte_coluna (id),
  CONSTRAINT fk_regra_dominio  FOREIGN KEY (dominio_id)      REFERENCES dominio (id),

  -- uma coluna de origem é mapeada uma vez; um campo de destino recebe uma
  -- coluna por fonte
  CONSTRAINT uk_regra_coluna   UNIQUE (fonte_coluna_id),
  CONSTRAINT uk_regra_destino  UNIQUE (fonte_id, destino_tabela, campo_destino),

  CONSTRAINT ck_regra_tipo     CHECK (tipo_dado IN
        ('TEXTO','INTEIRO','DECIMAL','DATA','BOOLEANO','GEOMETRIA')),
  CONSTRAINT ck_regra_flags    CHECK (
        obrigatorio IN (0,1) AND chave IN (0,1) AND bloquear_regressao IN (0,1)
        AND validar_cpf_cnpj IN (0,1) AND recortar_pr IN (0,1)),
  CONSTRAINT ck_regra_polgeo   CHECK (politica_geometria IN
        ('QUARENTENA','CORRIGIR_E_REGISTRAR')),
  CONSTRAINT ck_regra_refcruz  CHECK (referencia_cruzada IN
        ('municipio','imovel_rural')),
  CONSTRAINT ck_regra_chave    CHECK (chave = 0 OR obrigatorio = 1),
  CONSTRAINT ck_regra_geo      CHECK (
        (tipo_dado = 'GEOMETRIA' AND politica_geometria IS NOT NULL)
        OR (tipo_dado <> 'GEOMETRIA' AND politica_geometria IS NULL AND recortar_pr = 0))
);


--------------------------------------------------------------------------------
-- SEÇÃO 2 — ÍNDICES
--------------------------------------------------------------------------------
-- Oracle não indexa FK sozinho. As FKs fonte_id, fonte_coluna_id e dominio_id
-- de dominio_valor / fonte_coluna / regra_campo já são cobertas pelos índices
-- dos UNIQUE acima. Só falta dominio_id em regra_campo: sem este índice, DELETE
-- em dominio pega lock de tabela em regra_campo.
--------------------------------------------------------------------------------

CREATE INDEX ix_regra_dominio ON regra_campo (dominio_id);


--------------------------------------------------------------------------------
-- SEÇÃO 3 — STATUS DO ARQUIVO: AGUARDANDO_MAPEAMENTO
--------------------------------------------------------------------------------
-- A DAG processar_arquivo (Tarefa 1) marca o arquivo assim quando a fonte ainda
-- não tem mapeamento, e a tela de arquivos (Tarefa 4) exibe esse status.
--
-- O nome tem 21 caracteres e a coluna era VARCHAR2(20 CHAR): por isso o MODIFY.
-- O CHECK é recriado com a lista da V1 mais o valor novo.
--------------------------------------------------------------------------------

-- Remove o CHECK de status pelo conteúdo, e não pelo nome: se ele não existir
-- (ou tiver outro nome no banco de alguém), o bloco simplesmente não faz nada,
-- em vez de derrubar a migration com ORA-02443.
BEGIN
  FOR c IN (SELECT constraint_name
              FROM user_constraints
             WHERE table_name = 'ARQUIVO_BRUTO'
               AND constraint_type = 'C'
               AND search_condition_vc LIKE '%PENDENTE%') LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE arquivo_bruto DROP CONSTRAINT ' || c.constraint_name;
  END LOOP;
END;
/

-- ORA-30556: ix_arquivo_status (status, recebido_em) é um índice FUNCIONAL, porque
-- recebido_em é TIMESTAMP WITH TIME ZONE, e o Oracle não deixa alterar uma coluna
-- coberta por índice funcional. Derruba, altera a coluna e recria o índice
-- exatamente como na V1.
DROP INDEX ix_arquivo_status;

ALTER TABLE arquivo_bruto MODIFY (status VARCHAR2(30 CHAR));

CREATE INDEX ix_arquivo_status ON arquivo_bruto (status, recebido_em);

ALTER TABLE arquivo_bruto ADD CONSTRAINT ck_arquivo_status CHECK (status IN
  ('PENDENTE','RECEBIDO','PROCESSANDO','PROCESSADO','REJEITADO','AGUARDANDO_MAPEAMENTO'));


