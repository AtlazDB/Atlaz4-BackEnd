COMMENT ON COLUMN regra_campo.destino_tabela        IS 'Tabela de destino da gravação, por exemplo imovel_rural.';
COMMENT ON COLUMN regra_campo.campo_destino         IS 'Campo da tabela de destino, por exemplo cod_imovel.';
COMMENT ON COLUMN regra_campo.chave                 IS '1 = compõe a chave de negócio (erro de chave duplicada). Exige obrigatorio = 1.';
COMMENT ON COLUMN regra_campo.bloquear_regressao    IS '1 = aplica a regra de bloqueio de regressão. A semântica fica no pkg_qualidade.';
COMMENT ON COLUMN regra_campo.politica_geometria    IS 'QUARENTENA ou CORRIGIR_E_REGISTRAR. Só para tipo_dado = GEOMETRIA.';
COMMENT ON COLUMN regra_campo.recortar_pr           IS '1 = recorta a geometria pelo polígono do Paraná.';
COMMENT ON COLUMN regra_campo.referencia_cruzada    IS 'Integridade cruzada: nome da tabela referenciada (lista fixa: municipio, imovel_rural).';

COMMENT ON COLUMN arquivo_bruto.status              IS 'PENDENTE -> RECEBIDO -> PROCESSANDO -> PROCESSADO | REJEITADO | AGUARDANDO_MAPEAMENTO.';


