--------------------------------------------------------------------------------
-- SEÇÃO 1 — INPUT_FEATURE
--------------------------------------------------------------------------------
-- Destino genérico do processamento (pkg_tratada.gravar_aprovados): qualquer
-- fonte nova grava aqui pelo mapeamento, sem tabela própria. A fonte de cada
-- linha vem pela versão: dataset_versao -> execucao -> arquivo_bruto -> fonte.
--
-- Sem cod_imovel de propósito: na carga-retrato, com cod_imovel mapeado, o
-- gravar_aprovados apaga as linhas de outras versões com o mesmo código sem
-- olhar o conjunto, ou seja, apagaria dados de outras fontes.
--------------------------------------------------------------------------------
CREATE TABLE input_feature (
  id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  dataset_versao_id NUMBER             NOT NULL,
  geometria         SDO_GEOMETRY       NOT NULL,
  categoria         VARCHAR2(120 CHAR),
  data_referencia   TIMESTAMP,
  valor             NUMBER(14,4),
  criado_em         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_input_feature        PRIMARY KEY (id),
  CONSTRAINT fk_input_feature_versao FOREIGN KEY (dataset_versao_id) REFERENCES dataset_versao (id)
);

CREATE INDEX ix_input_feature_versao ON input_feature (dataset_versao_id);

-- Mesma tolerância e SRID da V12. O COMMIT antes do CREATE INDEX é obrigatório
-- (ORA-13203 sem ele).
INSERT INTO USER_SDO_GEOM_METADATA (TABLE_NAME, COLUMN_NAME, DIMINFO, SRID)
VALUES ('INPUT_FEATURE', 'GEOMETRIA',
        SDO_DIM_ARRAY(SDO_DIM_ELEMENT('LONGITUDE', -180, 180, 0.05),
                      SDO_DIM_ELEMENT('LATITUDE',  -90,   90, 0.05)), 4326);
COMMIT;

CREATE INDEX ix_input_feature_geometria ON input_feature (geometria)
  INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

--------------------------------------------------------------------------------
-- SEÇÃO 2 — INDICATOR_DEFINITION
--------------------------------------------------------------------------------
-- O indicador que o usuário cadastra: de qual fonte lê, qual modelo de cálculo
-- usa, os parâmetros e as faixas de status. Não é apagado, só desativado.
--------------------------------------------------------------------------------
CREATE TABLE indicator_definition (
  code              VARCHAR2(10 CHAR)   NOT NULL,
  name              VARCHAR2(120 CHAR)  NOT NULL,
  unit              VARCHAR2(12 CHAR)   NOT NULL,
  description       VARCHAR2(1000 CHAR),
  fonte_id          NUMBER              NOT NULL,
  calculation_model VARCHAR2(20 CHAR)   NOT NULL,
  parameters        VARCHAR2(4000 CHAR) DEFAULT '{}' NOT NULL,
  ranges            VARCHAR2(4000 CHAR) NOT NULL,
  active            NUMBER(1)           DEFAULT 1 NOT NULL,
  created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_indicator_definition PRIMARY KEY (code),
  CONSTRAINT fk_indicator_def_fonte  FOREIGN KEY (fonte_id) REFERENCES fonte (id),
  CONSTRAINT ck_indicator_def_code   CHECK (REGEXP_LIKE(code, '^[A-Z][A-Z0-9]{1,9}$')),
  CONSTRAINT ck_indicator_def_model  CHECK (calculation_model IN ('POINT_DENSITY', 'AREA_COVERAGE')),
  CONSTRAINT ck_indicator_def_params CHECK (parameters IS JSON),
  CONSTRAINT ck_indicator_def_ranges CHECK (ranges IS JSON),
  CONSTRAINT ck_indicator_def_active CHECK (active IN (0, 1))
);


--------------------------------------------------------------------------------
-- SEÇÃO 3 — INDICATOR_RESULT
--------------------------------------------------------------------------------
-- Um resultado por imóvel, indicador e versões usadas. Como no indicador_imovel
-- (V12), guarda as duas versões e os dois lados da conta, para explicar o
-- número depois mesmo que o imóvel ou o insumo mudem numa carga nova.
-- Sem FK para imovel_rural, pelo mesmo motivo da car_reserva_legal (V12).
--------------------------------------------------------------------------------
CREATE TABLE indicator_result (
  id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  indicator_code    VARCHAR2(10 CHAR)  NOT NULL,
  cod_imovel        VARCHAR2(80 CHAR)  NOT NULL,
  dataset_versao_id NUMBER             NOT NULL,
  versao_imovel_id  NUMBER             NOT NULL,
  value             NUMBER(14,4),
  status            VARCHAR2(12 CHAR)  NOT NULL,
  numerator         NUMBER(14,4),
  area_imovel_ha    NUMBER(14,4),
  calculated_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_indicator_result         PRIMARY KEY (id),
  CONSTRAINT fk_indicator_res_def        FOREIGN KEY (indicator_code)    REFERENCES indicator_definition (code),
  CONSTRAINT fk_indicator_res_versao     FOREIGN KEY (dataset_versao_id) REFERENCES dataset_versao (id),
  CONSTRAINT fk_indicator_res_ver_imovel FOREIGN KEY (versao_imovel_id)  REFERENCES dataset_versao (id),
  CONSTRAINT ck_indicator_res_status     CHECK (status IN ('CONFORME', 'ALERTA', 'CRITICO', 'VALIDACAO')),
  CONSTRAINT uk_indicator_result         UNIQUE (indicator_code, cod_imovel, dataset_versao_id, versao_imovel_id)
);



--------------------------------------------------------------------------------
-- SEÇÃO 4 — COMENTÁRIOS NO DICIONÁRIO DE DADOS
--------------------------------------------------------------------------------
COMMENT ON TABLE input_feature        IS 'Destino genérico das fontes novas (sem tabela própria), gravado pelo mapeamento.';
COMMENT ON TABLE indicator_definition IS 'Indicador cadastrado pelo usuário: fonte, modelo de cálculo, parâmetros e faixas de status.';
COMMENT ON TABLE indicator_result     IS 'Resultado dos indicadores cadastrados, por imóvel e versões usadas.';

COMMENT ON COLUMN input_feature.categoria            IS 'Valor de texto mapeado da fonte, usado no filtro do indicador (ex.: satélite).';
COMMENT ON COLUMN input_feature.data_referencia      IS 'Data da observação, quando a fonte tem.';
COMMENT ON COLUMN input_feature.valor                IS 'Número declarado pela fonte, quando tem (ex.: área).';
COMMENT ON COLUMN indicator_definition.parameters    IS 'JSON com os parâmetros do modelo (fator, filtro por categoria).';
COMMENT ON COLUMN indicator_definition.ranges        IS 'JSON com as faixas de status, em ordem: [{status, limite, incluir_limite}, ..., {status}].';
COMMENT ON COLUMN indicator_result.dataset_versao_id IS 'Versão do insumo (input_feature) usada no cálculo.';
COMMENT ON COLUMN indicator_result.versao_imovel_id  IS 'Versão do conjunto imoveis_rurais usada no cálculo.';
COMMENT ON COLUMN indicator_result.numerator         IS 'POINT_DENSITY: quantidade de pontos. AREA_COVERAGE: área da interseção em ha.';

