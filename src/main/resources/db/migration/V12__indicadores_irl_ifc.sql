--------------------------------------------------------------------------------
-- SEÇÃO 1 — REGRA_CALCULO
--------------------------------------------------------------------------------
-- A regra é versionada como os dados: mudar a fórmula ou um limite cria uma
-- versão nova (IRL v2) e desativa a anterior, e os resultados antigos continuam
-- apontando para a regra que os produziu. Os parâmetros ficam em JSON para cada
-- indicador ter os seus sem uma coluna por parâmetro.
--------------------------------------------------------------------------------
CREATE TABLE regra_calculo (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  indicador     VARCHAR2(10 CHAR)   NOT NULL,
  versao        NUMBER(4)           NOT NULL,
  codigo        VARCHAR2(40 CHAR)   NOT NULL,
  nome          VARCHAR2(120 CHAR)  NOT NULL,
  unidade       VARCHAR2(12 CHAR)   NOT NULL,
  formula       VARCHAR2(400 CHAR)  NOT NULL,
  descricao     VARCHAR2(1000 CHAR) NOT NULL,
  parametros    VARCHAR2(4000 CHAR) NOT NULL,
  ativa         NUMBER(1)           DEFAULT 1 NOT NULL,
  vigente_desde TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_regra_calculo     PRIMARY KEY (id),
  CONSTRAINT uk_regra_calculo     UNIQUE (indicador, versao),
  CONSTRAINT ck_regra_indicador   CHECK (indicador IN
        ('ICV','IRL','IAPP','ISAP','IAE','IDESMAT','IFC')),
  CONSTRAINT ck_regra_parametros  CHECK (parametros IS JSON),
  CONSTRAINT ck_regra_ativa       CHECK (ativa IN (0,1)),
  CONSTRAINT ck_regra_versao      CHECK (versao > 0)
);

-- Mínimo de 20% vale para a Mata Atlântica e o Cerrado do Paraná: fora da
-- Amazônia Legal o Código Florestal (Lei 12.651/2012, art. 12) não diferencia.
INSERT INTO regra_calculo (indicador, versao, codigo, nome, unidade, formula, descricao, parametros)
VALUES (
  'IRL', 1, 'RN-IRL-Min20pct', 'Reserva Legal', '%',
  'IRL = soma da área de RL declarada (ha) / área declarada do imóvel (ha) x 100',
  'Soma das áreas de Reserva Legal declaradas no CAR para o imóvel, dividida pela área '
  || 'declarada do imóvel. Conforme a partir de 20% (Mata Atlântica e Cerrado, fora da '
  || 'Amazônia Legal); abaixo disso, Crítico. O saldo é a área de RL menos 20% da área do '
  || 'imóvel: positivo é excedente, negativo é déficit.',
  '{"percentual_minimo": 20}'
);

-- Só o satélite de referência do INPE: o mesmo incêndio aparece uma vez por
-- satélite que passou, e somar todos inflaria a contagem. O AQUA_M-T é o que
-- o INPE usa na série histórica (conferido contra focos_br_ref_2025).
INSERT INTO regra_calculo (indicador, versao, codigo, nome, unidade, formula, descricao, parametros)
VALUES (
  'IFC', 1, 'RN-IFC-Queimadas', 'Focos de calor', 'focos/1000ha',
  'IFC = focos dentro do imóvel nos últimos 12 meses / área declarada do imóvel (ha) x 1000',
  'Focos de calor do satélite de referência do INPE (AQUA_M-T) que tocam o contorno do '
  || 'imóvel nos últimos 12 meses, a cada 1.000 hectares. Sem focos: Conforme; abaixo de 20: '
  || 'Alerta; 20 ou mais: Crítico.',
  '{"por_hectares": 1000, "janela_meses": 12, "satelite": "AQUA_M-T", "limite_critico": 20}'
);


--------------------------------------------------------------------------------
-- SEÇÃO 2 — CAR_RESERVA_LEGAL
--------------------------------------------------------------------------------
-- Um polígono de RL por linha: o mesmo imóvel pode ter vários. Sem FK para
-- imovel_rural de propósito — o arquivo do SICAR traz imóveis que não foram
-- carregados, e a FK derrubaria a carga inteira.
--
-- Guarda o estado atual por imóvel, como imovel_rural: uma carga nova substitui
-- os polígonos dos imóveis que vieram nela. O arquivo original continua na zona
-- bruta, e cada indicador guarda a versão que usou.
--------------------------------------------------------------------------------
CREATE TABLE car_reserva_legal (
  id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  cod_imovel        VARCHAR2(80 CHAR)  NOT NULL,
  municipio         VARCHAR2(160 CHAR),
  area_ha           NUMBER(14,4)       NOT NULL,
  situacao          VARCHAR2(20 CHAR),
  geometria         SDO_GEOMETRY       NOT NULL,
  dataset_versao_id NUMBER             NOT NULL,
  criado_em         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_car_reserva_legal PRIMARY KEY (id),
  CONSTRAINT fk_car_rl_versao     FOREIGN KEY (dataset_versao_id) REFERENCES dataset_versao (id),
  CONSTRAINT ck_car_rl_area       CHECK (area_ha >= 0)
);

CREATE INDEX ix_car_rl_imovel    ON car_reserva_legal (cod_imovel);
CREATE INDEX ix_car_rl_municipio ON car_reserva_legal (UPPER(municipio));
CREATE INDEX ix_car_rl_versao    ON car_reserva_legal (dataset_versao_id);


--------------------------------------------------------------------------------
-- SEÇÃO 3 — FOCO_CALOR
--------------------------------------------------------------------------------
-- Um ponto por detecção, de qualquer satélite: a regra é que escolhe qual
-- conta. id_inpe é o identificador do próprio INPE e torna a recarga de um mês
-- idempotente. data_hora fica em UTC, como vem no arquivo (data_hora_gmt).
--------------------------------------------------------------------------------
CREATE TABLE foco_calor (
  id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_inpe           VARCHAR2(64 CHAR)  NOT NULL,
  data_hora         TIMESTAMP          NOT NULL,
  satelite          VARCHAR2(40 CHAR)  NOT NULL,
  cod_ibge          VARCHAR2(7 CHAR),
  municipio         VARCHAR2(160 CHAR),
  bioma             VARCHAR2(60 CHAR),
  frp               NUMBER(10,2),
  geometria         SDO_GEOMETRY       NOT NULL,
  dataset_versao_id NUMBER             NOT NULL,
  CONSTRAINT pk_foco_calor    PRIMARY KEY (id),
  CONSTRAINT uk_foco_inpe     UNIQUE (id_inpe),
  CONSTRAINT fk_foco_versao   FOREIGN KEY (dataset_versao_id) REFERENCES dataset_versao (id)
);

-- A janela do IFC filtra por satélite e data antes do teste espacial
CREATE INDEX ix_foco_satelite_data ON foco_calor (satelite, data_hora);
CREATE INDEX ix_foco_versao        ON foco_calor (dataset_versao_id);


--------------------------------------------------------------------------------
