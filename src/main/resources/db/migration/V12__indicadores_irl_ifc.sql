CREATE INDEX ix_car_rl_geometria ON car_reserva_legal (geometria)
  INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

CREATE INDEX ix_foco_geometria ON foco_calor (geometria)
  INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;


--------------------------------------------------------------------------------
-- SEÇÃO 5 — INDICADOR_IMOVEL: regra, versões e memória de cálculo
--------------------------------------------------------------------------------
-- O indicador depende de duas versões de dados: a do imóvel (área, contorno) e
-- a do insumo (RL ou focos), que fica em dataset_versao_id. Guardar as duas, a
-- regra e os dois lados da conta é o que permite explicar o número depois,
-- mesmo que o imóvel mude numa carga nova do CAR.
--
--   numerador       ha de RL (IRL) ou quantidade de focos (IFC)
--   area_imovel_ha  denominador: área declarada do imóvel no momento do cálculo
--   area_ha         IRL: saldo de RL em ha (positivo excedente, negativo déficit)
--------------------------------------------------------------------------------
ALTER TABLE indicador_imovel ADD (
  regra_calculo_id  NUMBER,
  versao_imovel_id  NUMBER,
  numerador         NUMBER(14,4),
  area_imovel_ha    NUMBER(14,4),
  area_ha           NUMBER(14,4),
  calculado_em      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

ALTER TABLE indicador_imovel ADD CONSTRAINT fk_indicador_regra
  FOREIGN KEY (regra_calculo_id) REFERENCES regra_calculo (id);

ALTER TABLE indicador_imovel ADD CONSTRAINT fk_indicador_versao_imovel
  FOREIGN KEY (versao_imovel_id) REFERENCES dataset_versao (id);

-- A chave antiga não distinguia a versão do imóvel nem a regra: um recálculo
-- depois de uma carga nova do CAR sobrescreveria o resultado anterior.
ALTER TABLE indicador_imovel DROP CONSTRAINT uk_indicador;

ALTER TABLE indicador_imovel ADD CONSTRAINT uk_indicador
  UNIQUE (cod_imovel, indicador, regra_calculo_id, dataset_versao_id, versao_imovel_id);

CREATE INDEX ix_indicador_regra ON indicador_imovel (regra_calculo_id);


--------------------------------------------------------------------------------
-- SEÇÃO 6 — FONTES DOS INSUMOS
--------------------------------------------------------------------------------
-- O processamento escolhe o leitor pela sigla da fonte. A RL do CAR é uma camada
-- separada no SICAR. Os focos ganham fonte própria: a INPE da V1 é a dos alertas
-- de desmatamento, outro produto do INPE (insumo do IDesmat, não do IFC).
--------------------------------------------------------------------------------
INSERT INTO fonte (nome, sigla, orgao, formato, periodicidade)
SELECT 'CAR - Reserva Legal (PR)', 'CAR-RL', 'Servico Florestal Brasileiro', 'SHP', 'eventual'
  FROM dual
 WHERE NOT EXISTS (SELECT 1 FROM fonte WHERE UPPER(sigla) = 'CAR-RL');

INSERT INTO fonte (nome, sigla, orgao, formato, periodicidade)
SELECT 'INPE - Focos de calor', 'INPE-FOCOS', 'INPE - Programa Queimadas', 'CSV', 'diaria'
  FROM dual
 WHERE NOT EXISTS (SELECT 1 FROM fonte WHERE UPPER(sigla) = 'INPE-FOCOS');

COMMIT;


