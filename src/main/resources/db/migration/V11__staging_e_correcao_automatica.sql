COMMENT ON COLUMN staging_registro.atributos     IS 'Colunas da linha em JSON, com os nomes de origem. O pkg_qualidade lê com JSON_VALUE. Nulo quando a linha só tem geometria.';
COMMENT ON COLUMN staging_registro.geometria_wkb IS 'Geometria em WKB, sem nenhuma correção. Convertida para SDO_GEOMETRY dentro do pkg_qualidade.';
COMMENT ON COLUMN staging_registro.status        IS 'PENDENTE -> APROVADO | REPROVADO, marcado pelo pkg_qualidade.validar.';

COMMENT ON TABLE correcao_automatica IS 'Geometria corrigida automaticamente pelo pkg_qualidade, com o antes e o depois. Sprint 2, Tarefa 2.';

COMMENT ON COLUMN correcao_automatica.numero_linha        IS 'Linha do registro no arquivo de origem.';
COMMENT ON COLUMN correcao_automatica.chave_natural       IS 'Chave de negócio do registro corrigido (ex.: cod_imovel), no mesmo formato da registro_quarentena.chave_natural.';
COMMENT ON COLUMN correcao_automatica.coluna             IS 'Coluna de destino cuja política é CORRIGIR_E_REGISTRAR.';
COMMENT ON COLUMN correcao_automatica.erro_original       IS 'Retorno do SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT antes da correção, ex.: 13349 [Element <1>] [Ring <1>][Edge <1>][Edge <3>].';
