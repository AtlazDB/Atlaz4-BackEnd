-- 1.1 STAGING_REGISTRO -------------------------------------------------------
-- A sala de espera da validação. A DAG processar_arquivo lê o arquivo em lotes
-- e grava cada linha aqui, crua, do jeito que veio. Depois o pkg_qualidade
-- valida tudo de uma vez dentro do Oracle e marca o status de cada linha.
--
-- A geometria chega em WKB (bytes) e só vira SDO_GEOMETRY dentro do pacote:
-- assim uma geometria que nem converte cai na quarentena, em vez de derrubar
-- o INSERT da DAG.
--
-- Tabela temporária por natureza: o passo finalizar da DAG apaga as linhas
-- da execução quando o processamento termina.
CREATE TABLE staging_registro (
  id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  execucao_id    NUMBER             NOT NULL,
  camada         VARCHAR2(260 CHAR),
  numero_linha   NUMBER(12)         NOT NULL,
  atributos      CLOB,
  geometria_wkb  BLOB,
  status         VARCHAR2(12 CHAR)  DEFAULT 'PENDENTE' NOT NULL,
  CONSTRAINT pk_staging_registro PRIMARY KEY (id),
  CONSTRAINT fk_staging_exe      FOREIGN KEY (execucao_id) REFERENCES execucao (id),
  CONSTRAINT uk_staging_linha    UNIQUE (execucao_id, camada, numero_linha),
  CONSTRAINT ck_staging_json     CHECK (atributos IS JSON),
  CONSTRAINT ck_staging_status   CHECK (status IN ('PENDENTE','APROVADO','REPROVADO'))
);


-- 1.2 CORRECAO_AUTOMATICA ----------------------------------------------------
-- A regra da Tarefa 2 é: nenhuma geometria é corrigida sem registro. Quando a
-- política da coluna é CORRIGIR_E_REGISTRAR, o pkg_qualidade corrige com
-- SDO_UTIL.RECTIFY_GEOMETRY e grava aqui o antes e o depois, junto com o erro
-- que o SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT apontou. É o que permite
-- auditar, e desfazer, qualquer correção.

CREATE TABLE correcao_automatica (
  id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  execucao_id          NUMBER             NOT NULL,
  numero_linha         NUMBER(12),
  chave_natural        VARCHAR2(80  CHAR),
  coluna               VARCHAR2(80  CHAR) NOT NULL,
  erro_original        VARCHAR2(400 CHAR) NOT NULL,
  geometria_original   SDO_GEOMETRY       NOT NULL,
  geometria_corrigida  SDO_GEOMETRY       NOT NULL,
  corrigido_em         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_correcao_automatica PRIMARY KEY (id),
  CONSTRAINT fk_correcao_exe        FOREIGN KEY (execucao_id) REFERENCES execucao (id)
);


--------------------------------------------------------------------------------
-- SEÇÃO 2 — ÍNDICES
--------------------------------------------------------------------------------

-- Todo acesso à staging é por execução: o validar lê as linhas, a gravação na
-- Tratada lê as APROVADAS e o finalizar apaga. Um índice só cobre os três.
CREATE INDEX ix_staging_execucao ON staging_registro (execucao_id, status);

-- As correções de uma execução (tela de execuções e conferência do teste)
CREATE INDEX ix_correcao_execucao ON correcao_automatica (execucao_id);


