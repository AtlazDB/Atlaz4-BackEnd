COMMENT ON TABLE staging_registro    IS 'Linhas cruas de um arquivo, à espera do pkg_qualidade. Temporária: apagada ao fim da execução. Sprint 2, Tarefa 2.';

COMMENT ON COLUMN staging_registro.camada        IS 'Arquivo de origem dentro do pacote (ex.: o .shp dentro do .zip). Nulo quando o pacote tem um arquivo só.';
