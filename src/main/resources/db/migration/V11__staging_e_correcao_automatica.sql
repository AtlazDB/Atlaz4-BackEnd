-- As tabelas de apoio do pkg_qualidade, que a DAG processar_arquivo chama
-- depois de carregar o arquivo em lotes:
--
--   staging_registro     as linhas lidas do arquivo, à espera da validação
--   staging_erro         os erros de cada linha (uma linha pode ter vários)
--   correcao_automatica  cada geometria que o motor corrigiu sozinho
--
-- O pkg_qualidade só classifica: marca cada linha como APROVADO ou REPROVADO,
-- grava os erros em staging_erro e a geometria pronta em staging_registro.
-- Quem grava na Zona Tratada e na registro_quarentena é a DAG.
--
