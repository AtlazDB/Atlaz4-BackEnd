--------------------------------------------------------------------------------
-- O QUE ESTE SCRIPT FAZ
--------------------------------------------------------------------------------
-- A regra FORA_DO_RECORTE_TERRITORIAL (recortar_pr = 1) comparava cada registro
-- com os 399 municípios do PR. A malha do IAT tem 1,5 milhão de vértices: ~5 ms
-- por registro, ~30 min para os 333 mil focos de calor.
--
-- Esta tabela guarda o contorno do estado (a união dos municípios, simplificada)
-- cortado numa grade de 0,25°: as células do interior viram retângulos de 4
-- vértices e só as da divisa carregam um trecho do contorno (o maior pedaço tem
-- uns 500 vértices). Com o índice espacial, cada registro é comparado com um
-- pedaço pequeno: ~0,5 ms por registro (medido: 20 mil pontos em 9,5 s, com o
-- mesmo resultado da malha municipal).
--
-- Quem preenche é o pkg_quality.atualizar_recorte, chamado pelo próprio
-- validate quando a malha municipal muda de versão. Não é preciso rodar nada.
--
-- Precisão: o contorno é simplificado em ~20 m. Um registro a menos de ~30 m da
-- divisa, inteiramente do lado de fora, pode passar como "no PR". Para a regra
-- (reprovar o que está TOTALMENTE fora do estado) a diferença é desprezível.
--
--------------------------------------------------------------------------------
-- COMO RODAR
--------------------------------------------------------------------------------
-- Via Flyway, na subida da aplicação. Não editar depois de aplicado.
--------------------------------------------------------------------------------

CREATE TABLE recorte_territorial (
  id                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  uf                 VARCHAR2(2 CHAR)  NOT NULL,
  geometria          SDO_GEOMETRY      NOT NULL,
  versao_municipios  NUMBER,
  criado_em          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_recorte_territorial PRIMARY KEY (id)
);

-- O COMMIT antes do CREATE INDEX é obrigatório (mesmo motivo da V4).
INSERT INTO USER_SDO_GEOM_METADATA (TABLE_NAME, COLUMN_NAME, DIMINFO, SRID)
VALUES (
  'RECORTE_TERRITORIAL',
  'GEOMETRIA',
  SDO_DIM_ARRAY(
    SDO_DIM_ELEMENT('LONGITUDE', -180, 180, 0.05),
    SDO_DIM_ELEMENT('LATITUDE',  -90,   90, 0.05)
  ),
  4326
);
COMMIT;

CREATE INDEX ix_recorte_geometria ON recorte_territorial (geometria)
  INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

CREATE INDEX ix_recorte_uf ON recorte_territorial (uf);

COMMENT ON TABLE recorte_territorial IS 'Contorno da UF (união dos municípios, simplificada) cortado em grade de 0,25°, com índice espacial: a regra "fora do PR" do pkg_quality compara com um pedaço pequeno em vez da malha inteira. Preenchida pelo pkg_quality.atualizar_recorte.';
COMMENT ON COLUMN recorte_territorial.versao_municipios IS 'Maior dataset_versao_id da malha municipal usada: quando muda, o validate monta a grade de novo.';
